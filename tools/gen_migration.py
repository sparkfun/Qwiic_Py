#!/usr/bin/env python3
"""Generate MIGRATION.md from every driver README's "Migrating from 2.x" section.

The driver READMEs are the source of truth; this collects their migration
sections (and any "Renamed constants" section that follows) into one page.

Usage:
    gen_migration.py [--check]
"""

import argparse
import os
import re
import sys

from qwiic_repo import GITHUB_REPO, REPO_ROOT, load_drivers, read_text

OUTPUT = os.path.join(REPO_ROOT, "MIGRATION.md")

INTRO = """# Migrating from Qwiic_Py 2.x to 3.0

Version 3 gives every driver the same conventions (see [CONTRIBUTING.md](CONTRIBUTING.md)):

* **One name per method, PEP 8 style.** camelCase methods and duplicate aliases are gone, classes use the part number in capitals (`QwiicBME280`), and constants are `UPPER_CASE`.
* **No properties.** `sensor.connected` is `sensor.is_connected()`; every other property is replaced by its `get_`/`set_`/`read_` method.
* **No `print()` and no `time` module in drivers.** Errors are return values or exceptions; delays go through `qwiic_i2c` (`delay_ms`, `ticks_ms`, ...).
* **The bus can be the first argument.** `QwiicBME280(machine.I2C(1))` and `QwiicBME280(bus, 0x76)` work in every driver, as well as `i2c_bus=bus`, which replaces the 2.x `i2c_driver=` keyword. The bus can be the platform's own object (`machine.I2C`, `busio.I2C`, `smbus2.SMBus`). Code that passes the address first, or the bus positionally, is unchanged.
* **New install paths for MicroPython.** `mpremote mip install github:{repo}/drivers/<driver>` instead of `github:sparkfun/<old repo>`. PyPI names don't change.
* **`qwiic_i2c` 3.0.** See [its migration table](qwiic_i2c/README.md#migrating-from-2x). Most programs only notice `getI2CDriver()` becoming `get_i2c_bus()`.

Version 2 remains on PyPI (pin `<3`) for Python 3.6 and 3.7 users.

This page is generated by `tools/gen_migration.py` from each driver's README. The changes per driver:

"""


def migration_section(readme):
    lines = read_text(readme).splitlines()
    out = []
    inside = False
    for line in lines:
        heading = re.match(r"^(#{1,6})\s+(.*)", line)
        if heading:
            level, title = len(heading.group(1)), heading.group(2).strip().lower()
            if title.startswith("migrating from 2"):
                inside = True
                continue
            if inside and level <= 2 and not title.startswith("renamed constants"):
                break
            if inside:
                # Nest the driver's headings under its own section
                line = "#" * max(level + 1, 4) + " " + heading.group(2)
        if inside:
            if line.lstrip().startswith("<p align=") or "dark-logo-red-flame" in line or line.strip() == "</p>":
                continue
            out.append(line)
    while out and not out[-1].strip():
        out.pop()
    while out and not out[0].strip():
        out.pop(0)
    return out


def text():
    parts = [INTRO.format(repo=GITHUB_REPO)]
    missing = []
    for driver in load_drivers():
        section = migration_section(os.path.join(driver.path, "README.md"))
        if not section:
            missing.append(driver.name)
            continue
        parts.append("## %s\n\n" % driver.name)
        parts.append("\n".join(section) + "\n\n")
    if missing:
        print("No 'Migrating from 2.x' section in: " + ", ".join(missing), file=sys.stderr)
        sys.exit(1)
    return "".join(parts).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    new = text()
    current = read_text(OUTPUT) if os.path.exists(OUTPUT) else None
    if current == new:
        return
    if args.check:
        print("MIGRATION.md is out of date (run tools/gen_migration.py)", file=sys.stderr)
        sys.exit(1)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(new)
    print("wrote", os.path.relpath(OUTPUT))


if __name__ == "__main__":
    main()
