#!/usr/bin/env python3
"""Generate the qwiic meta-package registry and dependency list.

Writes:
- qwiic/qwiic_registry.py: (module, class, device name, addresses) for every
  driver class, so the meta-package never guesses names (Qwiic_Py#25).
- the dependencies list in qwiic/pyproject.toml: every driver package.
- docs/drivers.md: the driver index on the Read the Docs site.

Driver modules are imported on CPython to read device_name and
available_addresses; no hardware is needed.

Usage:
    gen_registry.py [--check]
"""

import argparse
import importlib
import os
import re
import sys

from qwiic_repo import REPO_ROOT, load_drivers, normalize_dist_name, read_text

META_DIR = os.path.join(REPO_ROOT, "qwiic")
REGISTRY = os.path.join(META_DIR, "qwiic_registry.py")
PYPROJECT = os.path.join(META_DIR, "pyproject.toml")
DRIVERS_DOC = os.path.join(REPO_ROOT, "docs", "drivers.md")

HEADER = '''# qwiic_registry.py
#
# Generated by tools/gen_registry.py. Do not edit.
#
# SPDX-License-Identifier: MIT

"""!
Every SparkFun Qwiic driver class: (module, class, device name, I2C addresses).
"""

DRIVERS = (
'''


def registry_entries():
    drivers = load_drivers()
    # Every driver directory, so drivers that use another driver can import it
    for driver in drivers:
        sys.path.insert(0, driver.path)
    entries = []
    for driver in drivers:
        if not driver.is_device:
            continue
        for module_name, class_name in driver.driver_classes():
            module = importlib.import_module(module_name)
            cls = getattr(module, class_name)
            addresses = tuple(int(a) for a in cls.available_addresses)
            entries.append((module_name, class_name, str(cls.device_name), addresses))
    return sorted(entries, key=lambda e: (e[2].lower(), e[1]))


def registry_text(entries):
    lines = [HEADER]
    for module_name, class_name, device_name, addresses in entries:
        address_text = "(%s)" % ", ".join("0x%02X" % a for a in addresses)
        if len(addresses) == 1:
            address_text = address_text[:-1] + ",)"
        lines.append("    (%r, %r, %r, %s),\n" % (module_name, class_name, device_name, address_text))
    lines.append(")\n")
    return "".join(lines)


def pyproject_text(current):
    requirements = []
    for driver in load_drivers():
        requirements.append('    "%s>=%s,<%d",' % (normalize_dist_name(driver.dist_name), driver.version, int(driver.version.split(".")[0]) + 1))
    block = "dependencies = [\n%s\n]" % "\n".join(requirements)
    return re.sub(r"dependencies = \[[^\]]*\]", lambda m: block, current, count=1)


def drivers_doc_text():
    platform_names = {"cpython": "CPython", "micropython": "MicroPython", "circuitpython": "CircuitPython"}
    lines = [
        "# Drivers",
        "",
        "Every SparkFun Qwiic Python driver. Install one with pip (CPython), mip (MicroPython) or circup",
        "(CircuitPython); see the [installation instructions](index.md#installation).",
        "",
        "| Driver | Description | Platforms | PyPI | API reference |",
        "| --- | --- | --- | --- | --- |",
    ]
    for driver in load_drivers():
        lines.append("| [%s](https://github.com/sparkfun/Qwiic_Py/tree/main/%s) | %s | %s | `%s` | [%s](https://docs.sparkfun.com/Qwiic_Py/%s/) |" % (
            driver.name, driver.rel_path,
            driver.pyproject["project"].get("description", "").replace("|", "/"),
            ", ".join(platform_names[p] for p in driver.platforms),
            normalize_dist_name(driver.dist_name), driver.version, driver.name,
        ))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report out-of-date files instead of writing")
    args = parser.parse_args()

    outputs = {
        REGISTRY: registry_text(registry_entries()),
        PYPROJECT: pyproject_text(read_text(PYPROJECT)),
        DRIVERS_DOC: drivers_doc_text(),
    }
    stale = []
    for path, text in outputs.items():
        current = read_text(path) if os.path.exists(path) else None
        if current == text:
            continue
        if args.check:
            stale.append(os.path.relpath(path))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote", os.path.relpath(path))
    if stale:
        print("Out of date (run tools/gen_registry.py): " + ", ".join(stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
