"""!
qwiic
=====
Find connected SparkFun Qwiic devices and create their driver objects.

The driver list comes from qwiic_registry (generated by tools/gen_registry.py),
so nothing is guessed from directory or class names. Driver modules are
imported only when they are needed, and drivers that aren't installed are
skipped, so this module works on CPython, MicroPython and CircuitPython with
any subset of drivers installed.

    import qwiic
    print(qwiic.list_devices())        # [(0x77, "Qwiic BME280", "QwiicBME280"), ...]
    sensor = qwiic.create_device("QwiicBME280")

New to Qwiic? Take a look at the entire [SparkFun Qwiic ecosystem](https://www.sparkfun.com/qwiic).
"""

import qwiic_i2c
from qwiic_registry import DRIVERS

__version__ = "3.0.0"

# Driver classes by name, filled in as they are imported
_classes = {}


def _load_class(module_name, class_name):
    """Import one driver class, or return None if its driver isn't installed."""
    if class_name not in _classes:
        try:
            module = __import__(module_name)
            _classes[class_name] = getattr(module, class_name)
        except ImportError:
            _classes[class_name] = None
    return _classes[class_name]


def _entries_for(addresses):
    """Registry entries whose devices can live at any of the addresses."""
    wanted = set(addresses)
    return [entry for entry in DRIVERS if wanted.intersection(entry[3])]


def get_driver_class(class_name):
    """!
    @param class_name: Driver class name, for example "QwiicBME280"
    @return The driver class, or None if it isn't in the registry or not installed
    """
    for module_name, name, _, _ in DRIVERS:
        if name == class_name:
            return _load_class(module_name, name)
    return None


def scan(i2c_bus=None):
    """!
    @param i2c_bus: Bus to scan (see qwiic_i2c.get_i2c_bus); the default bus when None
    @return **list of int** Addresses of every device on the bus
    """
    return list(qwiic_i2c.get_i2c_bus(i2c_bus).scan())


def list_available_drivers(addresses=None):
    """!
    @param addresses: Addresses to look up; every address when None
    @return **list of (address, device name, class name)** Drivers in the registry that
        can be at those addresses, whether or not they are installed
    """
    if addresses is None:
        addresses = range(0x08, 0x78)
    found = []
    for address in addresses:
        for _, class_name, device_name, device_addresses in DRIVERS:
            if address in device_addresses:
                found.append((address, device_name, class_name))
    return found


def list_devices(i2c_bus=None):
    """!
    @param i2c_bus: Bus to scan; the default bus when None
    @return **list of (address, device name, class name)** Possible drivers for every
        device that answers on the bus. Several drivers can share an address.
    """
    return list_available_drivers(scan(i2c_bus))


def get_devices(i2c_bus=None):
    """!
    Create a driver object for every device on the bus. When several installed
    drivers share an address, an object is created for each of them.

    @param i2c_bus: Bus to scan; the default bus when None
    @return **list** Driver objects
    """
    bus = qwiic_i2c.get_i2c_bus(i2c_bus)
    devices = []
    for address in bus.scan():
        for module_name, class_name, _, device_addresses in DRIVERS:
            if address in device_addresses:
                cls = _load_class(module_name, class_name)
                if cls is not None:
                    devices.append(cls(address=address, i2c_bus=bus))
    return devices


def create_device(device, i2c_bus=None):
    """!
    Create the driver object for one connected device.

    @param device: A class name ("QwiicBME280"), a device name ("Qwiic BME280"), an
        address (0x77), or an entry from list_devices()
    @param i2c_bus: Bus to use; the default bus when None
    @return The driver object
    @exception ValueError: No connected device matches, or several do
    """
    bus = qwiic_i2c.get_i2c_bus(i2c_bus)
    if isinstance(device, tuple):
        matches = [entry for entry in list_devices(bus) if entry == device]
    elif isinstance(device, int):
        matches = [entry for entry in list_devices(bus) if entry[0] == device]
    else:
        matches = [entry for entry in list_devices(bus) if device in (entry[1], entry[2])]
    if not matches:
        raise ValueError("No connected Qwiic device matches %r" % (device,))
    if len(matches) > 1:
        raise ValueError("Several connected Qwiic devices match %r: %r" % (device, matches))
    address, _, class_name = matches[0]
    cls = get_driver_class(class_name)
    if cls is None:
        raise ValueError("The driver for %s isn't installed" % class_name)
    return cls(address=address, i2c_bus=bus)


def __getattr__(name):
    """Let qwiic.QwiicBME280 and friends import their driver on first use."""
    cls = get_driver_class(name)
    if cls is None:
        raise AttributeError(name)
    return cls
